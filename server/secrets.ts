/**
 * Regenerates an individual key or all internal keys at once.
 */
export async function regenerateSecret(
  keyName: 'AUTH_SECRET' | 'CRON_SECRET' | 'ADMIN_API_KEY' | 'WORKDAY_ENCRYPTION_KEY' | 'ALL',
  actorUserId = 'usr_admin'
): Promise<{ success: boolean; regenerated: Record<string, string>; message: string }> {
  const regenerated: Record<string, string> = {};

  if (keyName === 'AUTH_SECRET' || keyName === 'ALL') {
    const newAuthSecret = crypto.randomBytes(32).toString('hex');
    await db.setSystemSecret('AUTH_SECRET', newAuthSecret);
    regenerated.AUTH_SECRET = newAuthSecret;
  }

  if (keyName === 'CRON_SECRET' || keyName === 'ALL') {
    const newCronSecret = crypto.randomBytes(32).toString('hex');
    await db.setSystemSecret('CRON_SECRET', newCronSecret);
    regenerated.CRON_SECRET = newCronSecret;
  }

  if (keyName === 'ADMIN_API_KEY' || keyName === 'ALL') {
    const newAdminKey = `aa_adm_${crypto.randomBytes(24).toString('base64url')}`;
    await db.setSystemSecret('ADMIN_API_KEY', newAdminKey);
    regenerated.ADMIN_API_KEY = newAdminKey;
  }

  if (keyName === 'WORKDAY_ENCRYPTION_KEY' || keyName === 'ALL') {
    const newWorkdayKey = crypto.randomBytes(32).toString('hex');
    await db.setSystemSecret('WORKDAY_ENCRYPTION_KEY', newWorkdayKey);
    regenerated.WORKDAY_ENCRYPTION_KEY = newWorkdayKey;
  }

  db.addAuditLog({
    userId: actorUserId,
    timestamp: new Date().toISOString(),
    category: 'security',
    action: 'SYSTEM_KEYS_REGENERATED',
    details: `Rotated keys: [${Object.keys(regenerated).join(', ')}]. Stored in persistent database.`,
    severity: 'warn',
  });

  return {
    success: true,
    regenerated,
    message: `Successfully regenerated ${Object.keys(regenerated).length} key(s). Persisted to database.`,
  };
}

/**
 * Allows the admin to save a runtime override for keys (e.g. GEMINI_API_KEY, GROQ_API_KEY)
 * without needing to access Vercel's masked environment settings.
 */
export async function setRuntimeOverride(
  keyName: string,
  value: string,
  actorUserId = 'usr_admin'
): Promise<{ success: boolean; message: string }> {
  const cleanVal = value.trim();
  await db.setSystemSecret(keyName, cleanVal);

  // Apply to process.env immediately if it's an active runtime key
  if (['GEMINI_API_KEY', 'GROQ_API_KEY', 'GOOGLE_CLIENT_ID', 'GOOGLE_CLIENT_SECRET'].includes(keyName)) {
    process.env[keyName] = cleanVal;
  }

  db.addAuditLog({
    userId: actorUserId,
    timestamp: new Date().toISOString(),
    category: 'security',
    action: 'RUNTIME_KEY_CONFIGURED',
    details: `Configured runtime secret for ${keyName}.`,
    severity: 'info',
  });

  return { success: true, message: `Runtime override for ${keyName} saved and applied.` };
}

