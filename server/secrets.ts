import crypto from 'crypto';
import { db } from './db.js';

export interface SystemKeyInfo {
  name: string;
  label: string;
  category: 'auth' | 'automation' | 'admin' | 'ai' | 'oauth' | 'database';
  isSet: boolean;
  source: 'Environment (Vercel/Hosting)' | 'Internal Auto-Generated' | 'Runtime Override' | 'Not Configured';
  isRegenerable: boolean;
  maskedPreview: string;
  fullValue?: string;
  description: string;
  usageGuide: string;
}

function maskString(val: string): string {
  if (!val || val.length === 0) return 'Not Configured';
  if (val.length <= 8) return '••••••••';
  const prefix = val.slice(0, 4);
  const suffix = val.slice(-4);
  return `${prefix}••••••••${suffix}`;
}

export function generateSecureToken(byteLength = 32, prefix = ''): string {
  const token = crypto.randomBytes(byteLength).toString('hex');
  return prefix ? `${prefix}${token}` : token;
}

export function generateApiKey(prefix = 'aa_cand_', byteLength = 20): string {
  const token = crypto.randomBytes(byteLength).toString('base64url');
  return `${prefix}${token}`;
}

/**
 * Returns the effective AUTH_SECRET used for signing session tokens and OAuth state.
 * Resolution hierarchy:
 * 1. process.env.AUTH_SECRET (e.g. from Vercel / hosting environment)
 * 2. db.getSystemSecret('AUTH_SECRET') (stored in database.json / Supabase)
 * 3. Auto-generated 32-byte hex secret (saved immediately to db so sessions survive restarts)
 */
export function getAuthSecret(): string {
  if (process.env.AUTH_SECRET && process.env.AUTH_SECRET.trim().length > 0) {
    return process.env.AUTH_SECRET.trim();
  }

  const stored = db.getSystemSecret('AUTH_SECRET');
  if (stored && stored.trim().length > 0) {
    return stored.trim();
  }

  // Auto-generate fresh persistent secret
  const autoGenerated = crypto.randomBytes(32).toString('hex');
  void db.setSystemSecret('AUTH_SECRET', autoGenerated);
  console.log('[secrets] Auto-generated persistent AUTH_SECRET stored in database');
  return autoGenerated;
}

